# 상위 10곳 검토(T16, 9/15)에서 실제로 걸린 것 + 반경 1km 내 흔히 보이는
# 대형 프랜차이즈를 추가했다. 상호명에 아래 문자열이 포함되면 제외한다
# (지점명 접미사 "OO점"·"OO지점"은 상관없이 브랜드명만 보면 된다).
FRANCHISE_BRANDS: tuple[str, ...] = (
    # 제과·디저트
    "뚜레쥬르", "파리바게뜨", "파리바게트", "던킨", "배스킨라빈스", "설빙",
    # 피자·튀김·그릴 (치킨 포함)
    "피자헛", "도미노피자", "미스터피자", "파파존스", "굽네", "교촌치킨", "교촌",
    "bhc", "BHC", "bbq", "BBQ", "네네치킨", "처갓집", "깐부치킨", "푸라닭",
    "노랑통닭", "호식이두마리치킨",
    # 버거·분식
    "롯데리아", "맘스터치", "버거킹", "맥도날드", "노브랜드버거", "써브웨이",
    "움버거", "김밥천국", "김가네", "바르다김선생", "죠스떡볶이", "엽기떡볶이",
    "신전떡볶이", "명랑핫도그",
    # 카페
    "스타벅스", "투썸플레이스", "이디야", "메가커피", "컴포즈커피", "빽다방",
    "커피빈", "할리스", "공차", "탐앤탐스", "카페베네", "엔제리너스",
    "매머드커피", "더벤티", "파스쿠찌", "스무디킹",
)


def is_likely_franchise(name: str | None) -> bool:
    """브랜드명 키워드 포함 여부로 판단한다. 상호명 속 띄어쓰기는 무시하고 본다."""
    if not name:
        return False
    n = name.replace(" ", "")
    return any(brand.replace(" ", "") in n for brand in FRANCHISE_BRANDS)
