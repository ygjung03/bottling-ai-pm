-- 2026-09-25 — 시연용(예시) 협력사 표시
--
-- 2차 기획안은 「폼이 들어왔고 + 1차에서 안을 골랐을 때」만 만들 수 있다. 제안서를
-- 보내지도 않았는데 2차가 나가는 일을 막기 위해서다.
--
-- 그런데 시연에서는 1차와 2차를 모두 보여줘야 하고, 지금 폼 값이 있는 곳은
-- 「테스트용 제과점」 하나뿐이며 그 협력사에는 채택 기록이 없다. 그 조합에서 2차를
-- 여는 것은 **시연용 협력사에만** 허용한다. 실제 협력사가 그 경로로 새면 안 된다.
--
-- 판별은 이름이 "테스트용" 으로 시작하는지로 한다. 상호 중간에 그 말이 들어간 가게는
-- 있을 수 있어도 그것으로 시작하는 실제 상호는 찾지 못했다 (9/25 확인).
-- 앞으로 시연용을 더 만들 때도 「테스트용 분식점」처럼 같은 규칙으로 짓는다.
ALTER TABLE partners ADD COLUMN IF NOT EXISTS is_seed BOOLEAN NOT NULL DEFAULT false;

COMMENT ON COLUMN partners.is_seed IS
  '시연용 가상 협력사(이름이 "테스트용"으로 시작). 화면이 예시 표시를 붙이고 2차 생성 제약을 푼다';

UPDATE partners SET is_seed = true WHERE name LIKE '테스트용%';
