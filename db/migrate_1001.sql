-- 협의로 정한 판매 방식 (남은_작업 ②-5)
--
-- 손님에게 메뉴를 파는 방식이다 — 단품 / 세트 / 포장. 폼 1 섹션 2 에서 A2 만 답한다.
-- A 는 보낸 안에, B/C 는 3안 도출에서 고른 안에 들어 있어 화면이 알고있다.
--
-- 선택지 문장을 그대로 넣는다. 「단품」·「세트」로 줄이지 않는 이유는 보기에
-- 「아직 정하지 않았습니다」와 기타 서술형이 있어서다. 줄이면 그 답이 사라진다.
-- 셋 중 하나로 맞추는 일은 화면이 한다.
--
-- 값이 비어 있으면 「방식이 안 정해졌다」는 뜻이고, 그때는 AI 가 가장 나은
-- 하나를 고른다. 어느 경우든 2차 기획안은 안 하나다.

ALTER TABLE partners ADD COLUMN IF NOT EXISTS agreed_approach TEXT;
COMMENT ON COLUMN partners.agreed_approach IS
  '협의로 정한 판매 방식. 폼 선택지 문장 그대로 (단품으로만 판매 / 맥주와 묶어 세트로 판매 / '
  '포장해서 가져갈 수 있게 판매 / 아직 정하지 않았습니다 / 기타 서술형). '
  'A2 만 폼에서 받는다. 비어 있으면 AI 가 고른다.';