-- 협력사 주소 (2026-10-05)
--
-- 블로그 후기에서 메뉴·가격을 모을 때, 가게 이름만으로 찾으면 전국의 같은
-- 이름 가게가 섞인다. 실제로 재 봤다 (10/5).
--
--   라쿤피자건대           전국 피자 글. 잠실·방이동이 섞인다
--   라쿤피자건대 광진구     그 가게 글이 1위로 올라온다
--
-- 주소가 있어야 「광진구」를 붙일 수 있다. 지금은 등록할 때 nearby_stores 에서
-- lat/lng 만 가져오고 주소는 버린다. 이름으로 되짚을 수도 있지만 같은 이름이
-- 둘이면 어느 쪽인지 알 수 없고, nearby_stores 에 없는 가게는 못 찾는다.
-- 등록하는 자리에서 함께 넣어 두는 것이 맞다.
--
-- [NULL 을 허용하지만 비어 있으면 수집이 제대로 안 된다]
-- 추천·메뉴로 찾기로 등록한 가게는 nearby_stores 에서 주소가 따라온다.
-- **직접 입력으로 등록한 가게는 주소를 받는 칸이 아직 없어 비게 된다.**
-- 그 가게는 이름만으로 찾게 되어 엉뚱한 글이 섞인다. 직접 입력 폼에 주소를
-- 받는 일이 남아 있다 (남은_작업 ㉛).
--
-- [동이 아니라 구인 이유]
-- nearby_stores.address 는 도로명 주소라 동이 없다 ("서울특별시 광진구
-- 뚝섬로34길 67"). 원 데이터의 지번 주소에는 있지만 수집할 때 버렸다
-- (ingest/nearby_stores.py:80 이 rdnmAdr 를 먼저 쓴다). 구만으로도 충분히
-- 걸러진다는 것을 위 실험에서 봤다.

ALTER TABLE partners ADD COLUMN IF NOT EXISTS address TEXT;

COMMENT ON COLUMN partners.address IS
  '등록할 때 nearby_stores 에서 함께 가져온 주소. 블로그 후기 검색어에 구 이름을 붙이는 데 쓴다. 직접 입력 등록은 아직 비어 있다';
