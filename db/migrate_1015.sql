-- 2026-10-15 — 폼 2 링크를 꺼낸 시각
--
-- 진행바 5번 「메뉴 재선정」의 하위 줄이 「미작성」인지 「대기중」인지를 가른다.
--
--   미작성   메뉴를 확정했어도 아직 링크를 꺼내지 않았다
--   대기중   링크를 꺼냈고 협력사 응답을 기다린다
--   완료     폼 2 가 들어와 agreed_menu 가 찼다
--
-- 전에는 「메뉴를 확정했는가」로 대신 갈랐다. 확정하자마자 「응답 대기」로 보여,
-- 아직 링크를 주지 않았는데 기다리는 중이라고 말하는 셈이었다.
--
-- 메뉴 확정 줄(round=2, final_output 이 빈 행)에 적는다. 그 줄에 폼 2 링크
-- 버튼이 있다.

ALTER TABLE plans ADD COLUMN IF NOT EXISTS form2_at TIMESTAMPTZ;

COMMENT ON COLUMN plans.form2_at IS
  '(B/C) 이 줄의 폼 2 링크를 꺼낸 시각. 진행바가 미작성·대기중을 가른다';
